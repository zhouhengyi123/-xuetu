  function detect() {
    try {
      const saved = Storage.get(KEY, null);
      if (saved && LANGS.indexOf(saved) >= 0) return saved;
    } catch (e) {}
    let l = '';
    try { l = (typeof navigator !== 'undefined' && navigator.language) || ''; } catch (e) {}
    try {
      if (!l && typeof require === 'function') {
        const e = require('electron');
        if (e && e.app && e.app.getLocale) l = e.app.getLocale();
      }
    } catch (e) {}
    const low = String(l || '').toLowerCase();
    if (low.indexOf('ja') === 0 || low.indexOf('jp') >= 0) return 'ja-JP';
    if (low.indexOf('ko') === 0 || low.indexOf('kr') >= 0) return 'ko-KR';
    return 'zh-CN';
  }

  function current() { return detect(); }

  function set(lang) {
    if (LANGS.indexOf(lang) < 0) return false;
    try { Storage.set(KEY, lang); return true; } catch (e) { return false; }
  }

  /** 翻译一个源中文串；字典没有就原样返回（不假装翻了） */
  function t(zh) {
    const lang = current();
    if (lang === 'zh-CN') return zh;
    const d = DICT[lang] || {};
    if (Object.prototype.hasOwnProperty.call(d, zh)) return d[zh];
    return zh;
  }

  function scopeNotice() { return SCOPE_NOTICE[current()] || SCOPE_NOTICE['zh-CN']; }
  function partialNotice() { return PARTIAL_NOTICE[current()] || ''; }

  /**
   * 把当前语言下需要翻译的静态 DOM 文案替换掉。
   * 采用「文本节点精确匹配」而非 innerHTML 重写，避免破坏事件绑定。
   */
  function applyDOM(root) {
    const lang = current();
    if (lang === 'zh-CN') return 0;      // 中文无需替换
    const d = DICT[lang] || {};
    const keys = Object.keys(d);
    if (!keys.length) return 0;
    const doc = (typeof document !== 'undefined') ? document : null;
    if (!doc) return 0;
    const base = root || doc;
    let n = 0;
    try {
      const walker = doc.createTreeWalker(base, 4 /* NodeFilter.SHOW_TEXT */);
      const nodes = [];
      while (walker.nextNode()) nodes.push(walker.currentNode);
      nodes.forEach(node => {
        const txt = node.nodeValue;
        if (!txt || !txt.trim()) return;
        let changed = txt;
        // 只替换整段文本完全等于字典 key 的，或作为独立短语出现的
        keys.forEach(zh => {
          if (changed === zh) changed = d[zh];
        });
        if (changed !== txt) { node.nodeValue = changed; n++; }
      });
      // html lang
      if (doc.documentElement) doc.documentElement.setAttribute('lang', lang);
    } catch (e) {}
    return n;
  }

  /** AI 输出语言指令（替换 dt-chat.js 里写死的中文强制句） */
